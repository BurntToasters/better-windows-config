/// <summary>Runs the real Node signer (node/minisign.mjs). Needs `node` on PATH.</summary>
internal static class NodeSigner
{
    public static string ScriptPath([CallerFilePath] string? thisFile = null) =>
        Path.GetFullPath(Path.Combine(Path.GetDirectoryName(thisFile!)!, "..", "..", "node", "minisign.mjs"));

    public static void Run(params string[] args)
    {
        var psi = new ProcessStartInfo("node")
        {
            UseShellExecute = false,
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            CreateNoWindow = true,
        };
        psi.ArgumentList.Add(ScriptPath());
        foreach (var arg in args)
        {
            psi.ArgumentList.Add(arg);
        }

        using var process = Process.Start(psi) ?? throw new InvalidOperationException("could not start node");
        _ = process.StandardOutput.ReadToEndAsync();
        var stderr = process.StandardError.ReadToEndAsync();
        if (!process.WaitForExit(TimeSpan.FromMinutes(5)))
        {
            process.Kill(entireProcessTree: true);
            throw new TimeoutException($"node minisign.mjs {args[0]} timed out");
        }

        if (process.ExitCode != 0)
        {
            throw new InvalidOperationException($"node minisign.mjs {args[0]} exited {process.ExitCode}: {stderr.Result}");
        }
    }
}

/// <summary>A key pair generated by the Node CLI. Secret key stays in Dir.</summary>
internal sealed record SigningKey(string Dir, string PublicKeyText, string TauriPublicKey)
{
    public static SigningKey Generate(string dir)
    {
        Directory.CreateDirectory(dir);
        NodeSigner.Run("keygen", dir);
        var text = File.ReadAllText(Path.Combine(dir, "minisign.pub"));
        return new SigningKey(dir, text, Sig.Tauri(text));
    }

    /// <summary>Key id bytes as stored in the public key packet (not the byte-reversed display hex).</summary>
    public byte[] KeyId => Sig.PublicKeyPacket(PublicKeyText)[2..10];
}

/// <summary>A file signed by the Node CLI: raw .minisig text and the base64 .sig envelope.</summary>
internal sealed record SignedFile(string FilePath, string Raw, string Envelope);

internal static class Signing
{
    public static SignedFile Sign(string file, SigningKey key, string trustedComment, bool legacy = false)
    {
        var args = new List<string> { "sign", file, key.Dir, "--trusted-comment", trustedComment };
        if (legacy)
        {
            args.Add("--legacy");
        }

        NodeSigner.Run(args.ToArray());
        return new SignedFile(file, File.ReadAllText(file + ".minisig"), File.ReadAllText(file + ".sig"));
    }
}

/// <summary>Byte-level helpers that build tampered signature text. LF input assumed unless noted.</summary>
internal static class Sig
{
    private const string Alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

    public static string[] Lines(string text) => text.TrimEnd('\n').Split('\n');

    public static string Join(IEnumerable<string> lines) => string.Join('\n', lines) + "\n";

    public static string Tauri(string text) => Convert.ToBase64String(Encoding.UTF8.GetBytes(text));

    public static byte[] PublicKeyPacket(string publicKeyText) => Convert.FromBase64String(Lines(publicKeyText)[1]);

    public static byte[] Packet(string raw) => Convert.FromBase64String(Lines(raw)[1]);

    public static byte[] GlobalOf(string raw) => Convert.FromBase64String(Lines(raw)[3]);

    public static string WithPacket(string raw, byte[] packet)
    {
        var lines = Lines(raw);
        lines[1] = Convert.ToBase64String(packet);
        return Join(lines);
    }

    public static string WithPacketLine(string raw, string line)
    {
        var lines = Lines(raw);
        lines[1] = line;
        return Join(lines);
    }

    public static string WithKeyId(string raw, byte[] keyId)
    {
        var packet = Packet(raw);
        keyId.CopyTo(packet, 2);
        return WithPacket(raw, packet);
    }

    public static byte[] WithAlgorithm(byte[] packet, string alg)
    {
        var copy = (byte[])packet.Clone();
        Encoding.ASCII.GetBytes(alg).CopyTo(copy, 0);
        return copy;
    }

    public static string WithTrustedComment(string raw, string comment)
    {
        var lines = Lines(raw);
        lines[2] = "trusted comment: " + comment;
        return Join(lines);
    }

    public static string WithUntrustedComment(string raw, string comment)
    {
        var lines = Lines(raw);
        lines[0] = comment;
        return Join(lines);
    }

    public static string WithGlobal(string raw, byte[] global)
    {
        var lines = Lines(raw);
        lines[3] = Convert.ToBase64String(global);
        return Join(lines);
    }

    /// <summary>
    /// Same decoded bytes as the 74-byte packet line, but one unused padding bit set.
    /// A 74-byte packet ends in one '=', so the third-to-last char carries 2 padding bits.
    /// </summary>
    public static string NonCanonicalPacketLine(string raw)
    {
        var lines = Lines(raw);
        var b64 = lines[1];
        var value = Alphabet.IndexOf(b64[^2]);
        lines[1] = b64[..^2] + Alphabet[value | 1] + b64[^1..];
        return Join(lines);
    }
}

/// <summary>A temp folder that is deleted at Dispose. Lives in the system temp folder.</summary>
internal sealed class TempDir : IDisposable
{
    public TempDir()
    {
        Root = Path.Combine(Path.GetTempPath(), "bwc-s5-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(Root);
    }

    public string Root { get; }

    public string Sub(string name) => Directory.CreateDirectory(Path.Combine(Root, name)).FullName;

    public string Write(string name, byte[] bytes)
    {
        var path = Path.Combine(Root, name);
        File.WriteAllBytes(path, bytes);
        return path;
    }

    public void Dispose()
    {
        try
        {
            Directory.Delete(Root, recursive: true);
        }
        catch (IOException)
        {
            // Best effort; the OS temp folder is cleaned eventually.
        }
        catch (UnauthorizedAccessException)
        {
            // Best effort.
        }
    }
}

internal static class Expect
{
    public static void Accepted(VerificationResult result, string trustedComment)
    {
        Assert.IsTrue(result.Ok, $"expected acceptance, got failure: {result.Failure}");
        Assert.AreEqual(trustedComment, result.TrustedComment);
        Assert.AreEqual(string.Empty, result.Failure);
    }

    public static void Rejected(VerificationResult result, string? reasonContains = null)
    {
        Assert.IsFalse(result.Ok, "expected rejection, but verification succeeded");
        Assert.IsFalse(string.IsNullOrWhiteSpace(result.Failure), "a rejection must carry a reason");
        Assert.IsNull(result.TrustedComment, "a rejected result must not expose a trusted comment");
        if (reasonContains is not null)
        {
            Assert.IsTrue(
                result.Failure.Contains(reasonContains, StringComparison.OrdinalIgnoreCase),
                $"expected reason containing '{reasonContains}', got: {result.Failure}");
        }
    }
}

internal static class Payloads
{
    public static byte[] Pattern(int length = 4096) =>
        Enumerable.Range(0, length).Select(i => (byte)(i * 31 + 7)).ToArray();
}
