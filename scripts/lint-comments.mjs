#!/usr/bin/env node
/**
 * Comment linter for C# sources under src/ and tests/.
 *
 * Rules:
 * - TODO, FIXME, HACK, and XXX are rejected as case-sensitive whole words.
 * - A single-line comment that only repeats the words on the next code line is
 *   rejected.
 * - Generic labels such as "// Helpers" are rejected.
 * - Prose comments are limited to 12 lines and 120 characters; XML doc
 *   comments are limited to 24 lines. License and tool directives are exempt.
 *
 * The parser skips normal, verbatim, interpolated, and raw string literals plus
 * character literals, so markers inside them are ignored. Comments inside an
 * interpolated string hole are not seen because the whole string is skipped.
 * XML doc comments are parsed as comments, so a marker there does fail.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT = "scripts/lint-comments.mjs";
const DEFAULT_ROOT = path.dirname(
  path.dirname(fileURLToPath(import.meta.url)),
);
const SOURCE_DIRECTORIES = ["src", "tests"];
const IGNORED_DIRECTORIES = new Set([
  ".git",
  "artifacts",
  "bin",
  "node_modules",
  "obj",
  "publish",
  "TestResults",
]);

const MAX_LENGTH = 120;
const MAX_PROSE_LINES = 12;
const MAX_DOC_LINES = 24;

const MARKER_PATTERN = /\b(TODO|FIXME|HACK|XXX)\b/;
const EXEMPT_PATTERN =
  /(?:@license|copyright|eslint|prettier|@ts-|istanbul|\bc8\b|coverage|rustfmt|clippy|SPDX|commentlint-disable|auto-generated)/i;
const GENERIC_LABEL_PATTERN =
  /^(?:imports?|exports?|constants?|variables?|types?|interfaces?|constructors?|getters?|setters?|methods?|helpers?|utilities?)\s*[:.]?$/i;
const GENERATED_FILE_PATTERN =
  /(?:<auto-generated|generated (?:code|file)|do not edit)/i;
const URL_PATTERN = /\b(?:https?|file):\/\/\S+/i;

const STOPWORDS = new Set([
  "a",
  "an",
  "and",
  "are",
  "as",
  "at",
  "be",
  "by",
  "for",
  "from",
  "has",
  "if",
  "in",
  "is",
  "it",
  "its",
  "of",
  "on",
  "or",
  "that",
  "the",
  "then",
  "this",
  "to",
  "was",
  "when",
  "which",
  "with",
]);

function printHelp() {
  console.log(`Usage:
  node ${SCRIPT} [--root <dir>] [--help]

Scans every .cs file under <root>/src and <root>/tests, skipping bin, obj,
artifacts, publish, TestResults, .git, and node_modules. Untracked source files
are included so the check runs before commit.

Rejected comment forms:
  TODO, FIXME, HACK, or XXX as a whole word (case-sensitive)
  a single-line comment that only repeats the next code line
  generic labels such as "// Helpers" or "// Constructor"
  prose comments longer than ${MAX_PROSE_LINES} lines or ${MAX_LENGTH} characters
  XML doc comments longer than ${MAX_DOC_LINES} lines

Limits: markers inside string and character literals are ignored. Comments
inside an interpolated string hole are not scanned. XML doc comments are
scanned as comments.

Options:
  --root <dir>  Repository root. Defaults to the parent of scripts/.
  --help        Show this help.

Exit codes: 0 clean, 1 findings, 2 argument error.`);
}

function parseArgs(argv) {
  const options = { root: DEFAULT_ROOT, help: false };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--help" || arg === "-h") {
      options.help = true;
      continue;
    }
    if (arg === "--root") {
      const value = argv[index + 1];
      if (value === undefined || value.startsWith("--")) {
        throw new Error("--root requires a directory");
      }
      options.root = path.resolve(value);
      index += 1;
      continue;
    }
    if (arg.startsWith("--root=")) {
      const value = arg.slice("--root=".length);
      if (!value) {
        throw new Error("--root requires a directory");
      }
      options.root = path.resolve(value);
      continue;
    }
    throw new Error(`unrecognized argument: ${arg}`);
  }

  return options;
}

function collectSourceFiles(root) {
  const files = [];

  function visit(directory) {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const absolute = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        if (!IGNORED_DIRECTORIES.has(entry.name)) visit(absolute);
        continue;
      }
      if (entry.isFile() && path.extname(entry.name).toLowerCase() === ".cs") {
        files.push(absolute);
      }
    }
  }

  for (const directoryName of SOURCE_DIRECTORIES) {
    const directory = path.join(root, directoryName);
    if (fs.existsSync(directory) && fs.statSync(directory).isDirectory()) {
      visit(directory);
    }
  }

  return files.sort();
}

function countNewlines(text) {
  let count = 0;
  for (const character of text) {
    if (character === "\n") count += 1;
  }
  return count;
}

function skipCharLiteral(source, start) {
  let index = start + 1;
  while (index < source.length) {
    const character = source[index];
    if (character === "\\") {
      index += 2;
      continue;
    }
    if (character === "'") return index + 1;
    if (character === "\n") return index;
    index += 1;
  }
  return index;
}

function skipString(source, start) {
  let index = start;
  let verbatim = false;

  while (source[index] === "$" || source[index] === "@") {
    if (source[index] === "$") {
      // Interpolated strings are skipped as a whole; holes are not parsed.
    } else {
      verbatim = true;
    }
    index += 1;
  }

  if (source[index] !== '"') return start;

  let quoteCount = 0;
  while (source[index + quoteCount] === '"') quoteCount += 1;

  if (quoteCount >= 3) {
    let cursor = index + quoteCount;
    while (cursor < source.length) {
      if (source[cursor] !== '"') {
        cursor += 1;
        continue;
      }
      let runLength = 0;
      while (source[cursor + runLength] === '"') runLength += 1;
      if (runLength >= quoteCount) return cursor + runLength;
      cursor += runLength;
    }
    return source.length;
  }

  let cursor = index + 1;
  while (cursor < source.length) {
    const character = source[cursor];
    if (verbatim) {
      if (character === '"') {
        if (source[cursor + 1] === '"') {
          cursor += 2;
          continue;
        }
        return cursor + 1;
      }
      cursor += 1;
      continue;
    }
    if (character === "\\") {
      cursor += 2;
      continue;
    }
    if (character === '"') return cursor + 1;
    cursor += 1;
  }

  return cursor;
}

/**
 * Split a source file into comment lines and a copy with comments blanked out.
 * The code copy keeps strings, so the restatement rule can still see identifiers
 * and literal text.
 */
function tokenize(source) {
  const codeCharacters = source.split("");
  const comments = [];
  let index = 0;
  let line = 1;

  function blank(start, end) {
    for (let position = start; position < end; position += 1) {
      if (codeCharacters[position] !== "\n" && codeCharacters[position] !== "\r") {
        codeCharacters[position] = " ";
      }
    }
  }

  function consume(nextIndex) {
    line += countNewlines(source.slice(index, nextIndex));
    index = nextIndex;
  }

  while (index < source.length) {
    const character = source[index];

    if (character === "/" && source[index + 1] === "/") {
      const isDoc = source.startsWith("///", index);
      const newline = source.indexOf("\n", index);
      const end = newline === -1 ? source.length : newline;
      const textStart = index + (isDoc ? 3 : 2);
      comments.push({
        startLine: line,
        endLine: line,
        text: source.slice(textStart, end).trim(),
        isDoc,
        kind: "line",
      });
      blank(index, end);
      index = end;
      continue;
    }

    if (character === "/" && source[index + 1] === "*") {
      const close = source.indexOf("*/", index + 2);
      const end = close === -1 ? source.length : close + 2;
      const raw = source.slice(index, end);
      let body = raw.slice(2);
      if (body.endsWith("*/")) body = body.slice(0, -2);

      const rawLines = body.split("\n");
      for (let offset = 0; offset < rawLines.length; offset += 1) {
        let text = rawLines[offset].replace(/\r$/, "");
        if (offset === 0) {
          text = text.replace(/^\*+!?\s?/, "");
        } else {
          text = text.replace(/^\s*\*?\s?/, "");
        }
        comments.push({
          startLine: line + offset,
          endLine: line + offset,
          text: text.trim(),
          isDoc: raw.startsWith("/**"),
          kind: "block",
        });
      }

      blank(index, end);
      consume(end);
      continue;
    }

    if (character === "'") {
      consume(Math.max(skipCharLiteral(source, index), index + 1));
      continue;
    }

    if (character === '"' || character === "@" || character === "$") {
      const next = skipString(source, index);
      if (next > index) {
        consume(next);
        continue;
      }
      index += 1;
      continue;
    }

    if (character === "\n") {
      line += 1;
    }
    index += 1;
  }

  return {
    comments,
    codeLines: codeCharacters.join("").split(/\r?\n/),
  };
}

function normalizeWords(text) {
  return text
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/[^A-Za-z0-9]+/g, " ")
    .toLowerCase()
    .split(/\s+/)
    .filter((word) => word.length > 0 && !STOPWORDS.has(word));
}

function nextCodeLine(codeLines, afterLine) {
  for (let lineNumber = afterLine + 1; lineNumber <= codeLines.length; lineNumber += 1) {
    const text = codeLines[lineNumber - 1].trim();
    if (text === "" || text.startsWith("#")) continue;
    return text;
  }
  return null;
}

function buildGroups(comments) {
  const groups = [];
  let current = [];

  for (const entry of comments) {
    const previous = current[current.length - 1];
    if (previous && entry.startLine <= previous.startLine + 1) {
      current.push(entry);
      continue;
    }
    if (current.length > 0) groups.push(current);
    current = [entry];
  }
  if (current.length > 0) groups.push(current);
  return groups;
}

function lintSource(source) {
  const { comments, codeLines } = tokenize(source);
  const findings = [];

  for (const entry of comments) {
    if (!entry.text) continue;

    const marker = entry.text.match(MARKER_PATTERN);
    if (marker) {
      findings.push({
        line: entry.startLine,
        message: `comment contains the ${marker[1]} marker; resolve it or remove the comment`,
      });
      continue;
    }

    const normalized = entry.text.replace(URL_PATTERN, "<url>");
    if (
      normalized.length > MAX_LENGTH &&
      !EXEMPT_PATTERN.test(entry.text)
    ) {
      findings.push({
        line: entry.startLine,
        message: `comment text is ${normalized.length} characters (maximum ${MAX_LENGTH}); shorten or wrap it`,
      });
    }
  }

  for (const group of buildGroups(comments)) {
    const combined = group.map((entry) => entry.text).join(" ");
    if (EXEMPT_PATTERN.test(combined)) continue;
    const isDoc = group.some((entry) => entry.isDoc);
    const limit = isDoc ? MAX_DOC_LINES : MAX_PROSE_LINES;

    if (group.length > limit) {
      findings.push({
        line: group[0].startLine,
        message: `${isDoc ? "documentation" : "prose"} comment has ${group.length} lines (maximum ${limit}); keep it focused or move detail to documentation`,
      });
    }

    if (
      group.length === 1 &&
      GENERIC_LABEL_PATTERN.test(group[0].text.trim())
    ) {
      findings.push({
        line: group[0].startLine,
        message: `generic section comment "${group[0].text.trim()}" is usually redundant; prefer clear names and structure`,
      });
    }
  }

  for (const entry of comments) {
    if (entry.kind !== "line" || entry.isDoc) continue;
    const commentWords = normalizeWords(entry.text);
    if (commentWords.length < 2 || commentWords.length > 12) continue;

    const codeLine = nextCodeLine(codeLines, entry.endLine);
    if (codeLine === null) continue;
    const codeWords = new Set(normalizeWords(codeLine));
    if (commentWords.every((word) => codeWords.has(word))) {
      findings.push({
        line: entry.startLine,
        message:
          "comment only restates the next code line; remove it or explain why",
      });
    }
  }

  findings.sort((left, right) => left.line - right.line);
  return findings;
}

function main(argv = process.argv.slice(2)) {
  let options;
  try {
    options = parseArgs(argv);
  } catch (error) {
    console.error(
      `lint-comments: ${
        error instanceof Error ? error.message : String(error)
      }`,
    );
    console.error(`Try: node ${SCRIPT} --help`);
    return 2;
  }

  if (options.help) {
    printHelp();
    return 0;
  }

  if (!fs.existsSync(options.root) || !fs.statSync(options.root).isDirectory()) {
    console.error(`lint-comments: root is not a directory: ${options.root}`);
    return 1;
  }

  const files = collectSourceFiles(options.root);
  let findingCount = 0;

  for (const filePath of files) {
    let source;
    try {
      source = fs.readFileSync(filePath, "utf8");
    } catch (error) {
      console.error(
        `lint-comments: could not read ${filePath}: ${
          error instanceof Error ? error.message : String(error)
        }`,
      );
      findingCount += 1;
      continue;
    }

    const firstLines = source.split("\n").slice(0, 8).join("\n");
    if (GENERATED_FILE_PATTERN.test(firstLines)) continue;

    const relative = path
      .relative(options.root, filePath)
      .split(path.sep)
      .join("/");

    for (const finding of lintSource(source)) {
      findingCount += 1;
      console.error(`${relative}:${finding.line}: ${finding.message}`);
    }
  }

  if (findingCount > 0) {
    console.error(
      `lint-comments: ${findingCount} finding(s) in ${files.length} scanned file(s).`,
    );
    return 1;
  }

  console.log(`lint-comments: ok (${files.length} scanned file(s)).`);
  return 0;
}

process.exitCode = main();
