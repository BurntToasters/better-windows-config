using System.Buffers.Binary;
using System.Security.Cryptography;
using System.Text;
using Microsoft.Win32;

namespace Bwc.Oracle.Capture;

// `seed`: deletes and recreates HKCU\Software\BWC-Oracle from SeedSpec, reads every value
// back raw and verifies type and bytes, then writes docs/parity/oracle/seed-tree.md.
internal static class SeedCommand
{
    internal static void Run(RepoPaths paths)
    {
        Console.WriteLine("seed: deleting and recreating HKCU\\Software\\BWC-Oracle");
        RegistryGuard.DeleteOracleTree();

        using (RegistryGuard.CreateOracleKey(string.Empty))
        {
        }

        foreach (SeedKey seedKey in SeedSpec.Keys)
        {
            string full = KeyFullPath(seedKey.Relative);
            using RegistryKey key = RegistryGuard.CreateOracleKey(seedKey.Relative);
            foreach (SeedValue value in seedKey.Values)
            {
                if (value.Exact)
                {
                    RegistryGuard.SetExactValue(key, full, value.Name, value.Type, value.Data);
                }
                else
                {
                    RegistryGuard.SetRawValue(key, full, value.Name, value.Type, value.Data);
                }
            }
        }

        Verify();
        WriteDoc(paths.SeedTreeDoc);
        Console.WriteLine($"seed: {SeedSpec.Keys.Count} keys written and verified, doc at {paths.SeedTreeDoc}");
    }

    internal static string KeyFullPath(string relative) =>
        relative.Length == 0 ? RegistryGuard.OracleRoot : RegistryGuard.OracleRoot + @"\" + relative;

    private static void Verify()
    {
        var expectedKeys = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (SeedKey seedKey in SeedSpec.Keys)
        {
            expectedKeys.Add(seedKey.Relative);
            using RegistryKey key = OpenOracle(seedKey.Relative);
            var names = key.GetValueNames();
            if (names.Length != seedKey.Values.Count)
            {
                throw new InvalidDataException($"seed verify: '{seedKey.Relative}' has {names.Length} values, expected {seedKey.Values.Count}.");
            }

            foreach (SeedValue value in seedKey.Values)
            {
                RegistryNative.RawValue? raw = RegistryNative.QueryRaw(key.Handle, value.Name);
                if (raw is null)
                {
                    throw new InvalidDataException($"seed verify: '{seedKey.Relative}\\{value.Name}' missing.");
                }

                if (raw.Value.Type != value.Type || !raw.Value.Data.AsSpan().SequenceEqual(value.Data))
                {
                    throw new InvalidDataException(
                        $"seed verify: '{seedKey.Relative}\\{value.Name}' stored type {raw.Value.Type} len {raw.Value.Data.Length}, expected type {value.Type} len {value.Data.Length}.");
                }
            }
        }

        CollectKeys(RegistryGuard.OracleRoot, string.Empty, expectedKeys);
        Console.WriteLine($"seed: verified {SeedSpec.Keys.Count} keys, all values match raw bytes");
    }

    private static void CollectKeys(string fullPath, string relative, HashSet<string> expected)
    {
        using RegistryKey key = OpenOracle(relative);
        foreach (string child in key.GetSubKeyNames())
        {
            string childRel = relative.Length == 0 ? child : relative + @"\" + child;
            if (!expected.Contains(childRel))
            {
                throw new InvalidDataException($"seed verify: unexpected key '{fullPath}\\{child}'.");
            }

            CollectKeys(fullPath, childRel, expected);
        }
    }

    private static RegistryKey OpenOracle(string relative)
    {
        string sub = relative.Length == 0 ? @"Software\BWC-Oracle" : @"Software\BWC-Oracle\" + relative;
        return Registry.CurrentUser.OpenSubKey(sub, writable: false)
            ?? throw new InvalidDataException($"seed verify: key '{sub}' does not exist.");
    }

    private static void WriteDoc(string path)
    {
        var sb = new StringBuilder();
        sb.Append("# BWC-Oracle seed tree\n\n");
        sb.Append("Generated by `Bwc.Oracle.Capture` while the export, metrics and capture commands seed the tree. Do not edit by hand; regenerate with `npm run oracle -- --only export`.\n\n");
        sb.Append("Root: `HKEY_CURRENT_USER\\Software\\BWC-Oracle`. Every value below was read back raw from the registry after writing and matches these bytes exactly.\n\n");
        sb.Append("Byte lengths are the stored REG_* data length. Strings show `\\0` for embedded NUL characters.\n");

        foreach (SeedKey seedKey in SeedSpec.Keys)
        {
            string title = seedKey.Relative.Length == 0 ? "(root)" : seedKey.Relative;
            sb.Append($"\n## `{title}`\n\n");
            sb.Append("| Value | Type | Bytes | Data | Notes |\n");
            sb.Append("|---|---|---:|---|---|\n");
            foreach (SeedValue value in seedKey.Values)
            {
                (string data, string notes) = Describe(value);
                string name = value.Name.Length == 0 ? "(Default)" : value.Name;
                sb.Append($"| `{Escape(name)}` | {RegType.Name(value.Type)} | {value.Data.Length} | {data} | {notes} |\n");
            }
        }

        Util.WriteUtf8NoBom(path, sb.ToString());
    }

    private static (string Data, string Notes) Describe(SeedValue value)
    {
        byte[] d = value.Data;
        switch (value.Type)
        {
            case RegType.Sz:
            case RegType.ExpandSz:
            case RegType.Link:
                return DescribeString(d);

            case RegType.MultiSz:
                return DescribeMultiSz(d);

            case RegType.Dword when d.Length == 4:
            {
                uint v = BinaryPrimitives.ReadUInt32LittleEndian(d);
                return ($"`0x{v:X8}` ({v})", string.Empty);
            }

            case RegType.Dword:
                return ($"`{Util.Hex(d)}`", $"wrong length: REG_DWORD with {d.Length} bytes");

            case RegType.DwordBigEndian:
            {
                uint v = BinaryPrimitives.ReadUInt32BigEndian(d);
                return ($"`{Util.Hex(d)}`", $"big-endian, value 0x{v:X8}");
            }

            case RegType.Qword when d.Length == 8:
            {
                ulong v = BinaryPrimitives.ReadUInt64LittleEndian(d);
                return ($"`0x{v:X16}` ({v})", string.Empty);
            }

            case RegType.Qword:
                return ($"`{Util.Hex(d)}`", $"wrong length: REG_QWORD with {d.Length} bytes");

            default:
                return (d.Length == 0 ? "(empty)" : $"`{Util.Hex(d)}`", string.Empty);
        }
    }

    private static (string Data, string Notes) DescribeString(byte[] d)
    {
        var notes = new List<string>();
        if (d.Length % 2 != 0)
        {
            return ($"`{Util.Hex(d)}`", "odd byte count, not UTF-16");
        }

        string text = Encoding.Unicode.GetString(d);
        if (d.Length == 0)
        {
            notes.Add("zero bytes, no NUL terminator");
        }
        else if (text.Length < 1 || text[^1] != '\0')
        {
            notes.Add("no terminating NUL");
        }

        int nul = text.IndexOf('\0');
        if (nul >= 0 && nul < text.Length - 1)
        {
            notes.Add("embedded NUL");
        }

        string shown = text.TrimEnd('\0');
        if (shown.Length > 200)
        {
            string digest = Convert.ToHexString(SHA256.HashData(d)).ToLowerInvariant();
            string prefix = shown[..60].Replace("\0", "\\0");
            notes.Add($"{shown.Length} chars, sha256 {digest}");
            return ($"`\"{Escape(prefix)}...\"`", string.Join("; ", notes));
        }

        string escaped = shown.Replace("\0", "\\0");
        return ($"`\"{Escape(escaped)}\"`", string.Join("; ", notes));
    }

    private static (string Data, string Notes) DescribeMultiSz(byte[] d)
    {
        if (d.Length % 2 != 0)
        {
            return ($"`{Util.Hex(d)}`", "odd byte count, not UTF-16");
        }

        string text = Encoding.Unicode.GetString(d);
        if (text == "\0" || text.Length == 0)
        {
            return ("`[]`", "empty list, single NUL terminator");
        }

        string body = text.EndsWith('\0') ? text[..^1] : text;
        string[] parts = body.Split('\0');
        var items = parts[..^1];
        string list = string.Join(", ", items.Select(s => $"\"{Escape(s)}\""));
        string notes = items.Any(s => s.Length == 0) ? "contains an empty string" : string.Empty;
        return ($"`[{list}]`", notes);
    }

    private static string Escape(string s) => s.Replace("|", "\\|");
}
