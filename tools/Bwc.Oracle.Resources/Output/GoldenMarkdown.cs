using System.Globalization;
using System.Text;
using Bwc.Oracle.Resources.Format;
using Bwc.Oracle.Resources.Model;

namespace Bwc.Oracle.Resources.Output;

/// Human-readable rendering of the golden model. Same data as the JSON, arranged for review.
internal static class GoldenMarkdown
{
    public static string Render(GoldenFile file)
    {
        var md = new Md();
        md.Line("# Classic regedit resource oracle");
        md.Line();
        md.Line("Generated by `tools/Bwc.Oracle.Resources` from classic `regedit.exe` and its `en-US` MUI resource file. Do not edit by hand.");
        md.Line("Untracked Microsoft content. Regenerate from the repository root with `npm run oracle -- --only resources`.");
        md.Line("The JSON file beside this one holds the same data in machine-readable form.");
        md.Line();

        md.Heading(2, "Sources");
        md.Table(
            ["Module", "Path", "Bytes", "SHA-256", "File version", "Product version"],
            file.Header.Sources.Select(s => new[]
            {
                Text(s.Module),
                Text(s.Path),
                s.SizeBytes.ToString(CultureInfo.InvariantCulture),
                Text(s.Sha256),
                Text(s.FileVersion),
                Text(s.ProductVersion),
            }));

        md.Heading(2, "Summary");
        md.Table(
            ["Module", "Menus", "Dialogs", "Accelerator tables", "Accelerator entries", "String blocks", "Strings", "Errors"],
            file.Modules.Select(m => new[]
            {
                Text(m.Module),
                m.Menus.Count.ToString(CultureInfo.InvariantCulture),
                m.Dialogs.Count.ToString(CultureInfo.InvariantCulture),
                m.Accelerators.Count.ToString(CultureInfo.InvariantCulture),
                m.Accelerators.Sum(a => a.Entries?.Count ?? 0).ToString(CultureInfo.InvariantCulture),
                m.StringTables.Count.ToString(CultureInfo.InvariantCulture),
                m.StringTables.Sum(s => s.Strings?.Count ?? 0).ToString(CultureInfo.InvariantCulture),
                m.ErrorCount.ToString(CultureInfo.InvariantCulture),
            }));

        foreach (ModuleDump module in file.Modules)
        {
            RenderModule(md, module);
        }

        return md.ToString();
    }

    private static void RenderModule(Md md, ModuleDump module)
    {
        md.Heading(2, $"Module {Code(module.Module)}");

        md.Heading(3, "Resource inventory");
        md.Table(
            ["Type", "ID / name", "Language", "Bytes", "Parsed here", "Load error"],
            module.ResourceTypes.SelectMany(t => t.Resources.Select(r => new[]
            {
                Text(t.Type),
                IdText(r.Id, r.Name),
                Text(r.LanguageTag),
                r.ByteLength.ToString(CultureInfo.InvariantCulture),
                IsParsedType(t.TypeId) ? "yes" : "no",
                Text(r.Error),
            })));

        md.Heading(3, "Menus");
        if (module.Menus.Count == 0)
        {
            md.Line("None.");
            md.Line();
        }
        foreach (MenuRecord menu in module.Menus)
        {
            RenderMenu(md, menu);
        }

        md.Heading(3, "Dialogs");
        if (module.Dialogs.Count == 0)
        {
            md.Line("None.");
            md.Line();
        }
        foreach (DialogRecord dialog in module.Dialogs)
        {
            RenderDialog(md, dialog);
        }

        md.Heading(3, "Accelerator tables");
        if (module.Accelerators.Count == 0)
        {
            md.Line("None.");
            md.Line();
        }
        foreach (AcceleratorRecord table in module.Accelerators)
        {
            RenderAccelerators(md, table);
        }

        md.Heading(3, "String table");
        RenderStrings(md, module);

        md.Heading(3, "Resource errors");
        RenderErrors(md, module);
    }

    private static void RenderMenu(Md md, MenuRecord menu)
    {
        md.Heading(4, $"{menu.Type} {IdText(menu.Id, menu.Name)} ({menu.LanguageTag})");
        if (menu.Error is not null)
        {
            md.Line($"- Error: {Text(menu.Error)}");
            md.Line();
            return;
        }

        string help = menu.HelpId is uint h ? $"; header help id {Decode.Hex32(h)}" : string.Empty;
        md.Line($"- Template: {menu.Template} (version {menu.TemplateVersion}){help}");
        md.Line();
        if (menu.Items is { Count: > 0 } items)
        {
            RenderItems(md, items, 0);
        }
        else
        {
            md.Line("- (no items)");
        }
        md.Line();
    }

    private static void RenderItems(Md md, List<MenuItemRecord> items, int depth)
    {
        string indent = new(' ', depth * 2);
        foreach (MenuItemRecord item in items)
        {
            if (item.Separator)
            {
                md.Line($"{indent}- *separator*");
            }
            else
            {
                string[] parts = item.Text.Split('\t', 2);
                string label = parts[0].Length == 0 ? "(empty label)" : Code(parts[0]);
                string accel = parts.Length == 2 ? $", accelerator {Code(parts[1])}" : string.Empty;

                var details = new List<string> { $"id {item.Id}" };
                if (item.Popup)
                {
                    details.Add("popup");
                }
                if (item.HelpId is uint help)
                {
                    details.Add($"help id {help}");
                }
                details.AddRange(Names(item.FlagNames, item.TypeNames, item.StateNames));

                md.Line($"{indent}- {label}{accel} ({string.Join(", ", details)})");
            }

            if (item.Children is { Count: > 0 } children)
            {
                RenderItems(md, children, depth + 1);
            }
        }
    }

    private static void RenderDialog(Md md, DialogRecord dialog)
    {
        md.Heading(4, $"{dialog.Type} {IdText(dialog.Id, dialog.Name)} ({dialog.LanguageTag})");
        if (dialog.Error is not null)
        {
            md.Line($"- Error: {Text(dialog.Error)}");
            md.Line();
            return;
        }

        string help = dialog.HelpId is uint h ? $"; help id {Decode.Hex32(h)}" : string.Empty;
        md.Line($"- Template: {dialog.Template}; style {dialog.Style}; exStyle {dialog.ExStyle}{help}");
        md.Line($"- Rectangle (dialog units): x {dialog.X}, y {dialog.Y}, cx {dialog.Cx}, cy {dialog.Cy}");
        md.Line($"- Caption: {OrNone(Text(dialog.Title))}");
        md.Line($"- Menu: {OrNone(Value(dialog.Menu))}; window class: {OrNone(Value(dialog.WindowClass))}");
        md.Line($"- Font: {FontText(dialog.Font)}");
        md.Line($"- Controls: {dialog.Controls?.Count ?? 0} present, {dialog.DeclaredControlCount} declared");
        md.Line();

        if (dialog.Controls is { Count: > 0 } controls)
        {
            md.Table(
                ["ID", "Class", "Text", "Style", "ExStyle", "Help ID", "X", "Y", "CX", "CY", "Creation data bytes"],
                controls.Select(c => new[]
                {
                    c.Id.ToString(CultureInfo.InvariantCulture),
                    OrNone(Value(c.WindowClass)),
                    OrNone(Value(c.Title)),
                    c.Style,
                    c.ExStyle,
                    c.HelpId is uint ch ? ch.ToString(CultureInfo.InvariantCulture) : "",
                    c.X.ToString(CultureInfo.InvariantCulture),
                    c.Y.ToString(CultureInfo.InvariantCulture),
                    c.Cx.ToString(CultureInfo.InvariantCulture),
                    c.Cy.ToString(CultureInfo.InvariantCulture),
                    c.CreationDataLength.ToString(CultureInfo.InvariantCulture),
                }));
        }
    }

    private static void RenderAccelerators(Md md, AcceleratorRecord table)
    {
        md.Heading(4, $"{table.Type} {IdText(table.Id, table.Name)} ({table.LanguageTag})");
        if (table.Error is not null)
        {
            md.Line($"- Error: {Text(table.Error)}");
            md.Line();
            return;
        }

        md.Table(
            ["Key", "Virtual key", "Flags", "Flag names", "Command"],
            (table.Entries ?? []).Select(e => new[]
            {
                e.Key.ToString(CultureInfo.InvariantCulture),
                Text(e.KeyName),
                e.Flags,
                string.Join(", ", e.FlagNames),
                e.Command.ToString(CultureInfo.InvariantCulture),
            }));
    }

    private static void RenderStrings(Md md, ModuleDump module)
    {
        var blocks = module.StringTables.Where(b => b.Strings is not null).ToList();
        foreach (IGrouping<string, StringBlockRecord> byLanguage in blocks.GroupBy(b => b.LanguageTag).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            md.Line($"Language {Code(byLanguage.Key)}:");
            md.Line();
            md.Table(
                ["ID", "Text"],
                byLanguage
                    .SelectMany(b => b.Strings!)
                    .OrderBy(s => s.Id)
                    .Select(s => new[] { s.Id.ToString(CultureInfo.InvariantCulture), Text(s.Text) }));
        }

        if (blocks.Count == 0)
        {
            md.Line("None.");
            md.Line();
        }
    }

    private static void RenderErrors(Md md, ModuleDump module)
    {
        var lines = new List<string>();
        foreach (TypeInventory type in module.ResourceTypes.Where(t => !IsParsedType(t.TypeId)))
        {
            foreach (InventoryEntry entry in type.Resources.Where(r => r.Error is not null))
            {
                lines.Add($"- {Code($"{type.Type} {IdText(entry.Id, entry.Name)} ({entry.LanguageTag})")}: {Text(entry.Error)}");
            }
        }
        foreach (ResourceRecord record in AllParsed(module).Where(r => r.Error is not null))
        {
            lines.Add($"- {Code($"{record.Type} {IdText(record.Id, record.Name)} ({record.LanguageTag})")}: {Text(record.Error)}");
        }

        if (lines.Count == 0)
        {
            md.Line("None.");
        }
        foreach (string line in lines)
        {
            md.Line(line);
        }
        md.Line();
    }

    private static IEnumerable<ResourceRecord> AllParsed(ModuleDump module)
    {
        foreach (ResourceRecord r in module.Menus) yield return r;
        foreach (ResourceRecord r in module.Dialogs) yield return r;
        foreach (ResourceRecord r in module.Accelerators) yield return r;
        foreach (ResourceRecord r in module.StringTables) yield return r;
    }

    private static bool IsParsedType(int? typeId) =>
        typeId is ResourceTypeNames.Menu or ResourceTypeNames.Dialog or ResourceTypeNames.Accelerator or ResourceTypeNames.StringTable;

    private static IEnumerable<string> Names(params IEnumerable<string>?[] groups)
    {
        foreach (IEnumerable<string>? group in groups)
        {
            if (group is null) continue;
            foreach (string name in group)
            {
                if (name is not ("MF_END" or "MF_POPUP"))
                {
                    yield return name;
                }
            }
        }
    }

    private static string FontText(FontRecord? font)
    {
        if (font is null)
        {
            return "(system default)";
        }
        string text = $"{font.PointSize} pt {Code(font.Typeface)}";
        if (font.Weight is int weight) text += $", weight {weight}";
        if (font.Italic is bool italic) text += italic ? ", italic" : ", not italic";
        if (font.Charset is int charset) text += $", charset {charset}";
        return text;
    }

    private static string IdText(int? id, string? name) =>
        id is int number ? number.ToString(CultureInfo.InvariantCulture) : name ?? "?";

    /// Text for a string-or-ordinal value. Ordinals show their number and a standard name when they have one.
    private static string Value(object? value) => value switch
    {
        null => string.Empty,
        string s => Text(s),
        OrdinalRef o => $"ordinal 0x{o.Ordinal:X4}" + (o.Name is null ? string.Empty : $" ({o.Name})"),
        _ => value.ToString() ?? string.Empty,
    };

    private static string OrNone(string value) => value.Length == 0 ? "(none)" : value;

    /// Inline code for a single-line value. Control characters are made visible first.
    private static string Code(string value)
    {
        string visible = Visible(value);
        int longestRun = 0;
        int run = 0;
        foreach (char c in visible)
        {
            run = c == '`' ? run + 1 : 0;
            longestRun = Math.Max(longestRun, run);
        }
        if (longestRun == 0)
        {
            return $"`{visible}`";
        }
        string fence = new('`', longestRun + 1);
        return $"{fence} {visible} {fence}";
    }

    /// Table-cell form of a value: code span with pipes escaped. Empty input gives an empty cell.
    private static string Text(string? value) =>
        string.IsNullOrEmpty(value) ? string.Empty : Code(value).Replace("|", "\\|", StringComparison.Ordinal);

    private static string Visible(string value)
    {
        var sb = new StringBuilder(value.Length);
        foreach (char c in value)
        {
            switch (c)
            {
                case '\t':
                    sb.Append("\\t");
                    break;
                case '\r':
                    sb.Append("\\r");
                    break;
                case '\n':
                    sb.Append("\\n");
                    break;
                default:
                    if (c < 0x20)
                    {
                        sb.Append($"\\x{(int)c:X2}");
                    }
                    else
                    {
                        sb.Append(c);
                    }
                    break;
            }
        }
        return sb.ToString();
    }

    private sealed class Md
    {
        private readonly StringBuilder _sb = new();

        public void Line(string text = "") => _sb.Append(text).Append('\n');

        public void Heading(int level, string text)
        {
            Line($"{new string('#', level)} {text}");
            Line();
        }

        public void Table(IReadOnlyList<string> headers, IEnumerable<string[]> rows)
        {
            Line($"| {string.Join(" | ", headers)} |");
            Line($"| {string.Join(" | ", headers.Select(_ => "---"))} |");
            foreach (string[] row in rows)
            {
                Line($"| {string.Join(" | ", row)} |");
            }
            Line();
        }

        public override string ToString() => _sb.ToString();
    }
}
